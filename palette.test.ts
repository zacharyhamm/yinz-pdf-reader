import {assert, assertEquals, loadPlugin, test} from 'yinz:testing';

test('static palette inventory launches the alias and releases dismissed handles', async () => {
  const plugin = await loadPlugin('./palette.ts', {replies: {RequestPluginPermissions: null, CommandPalette: null, RunAction: null}});
  await plugin.event({PermissionRequestResult: 'Granted'});
  const registration = plugin.paletteCommands.find(c => c.type === 'register');
  assert(registration?.type === 'register');
  assertEquals(registration.staticActions, true);
  const context = {clientId: 1, paneId: {Terminal: 7}, tabId: 1, currentProject: null};
  const scope = {registration: registration.registration, opening: 1, view: 0, revision: 1};
  await plugin.palette({type: 'discover', scope, context, query: '', source: null}, 1);
  const reply = plugin.paletteCommands.at(-1);
  assert(reply?.type === 'reply' && 'Ok' in reply.result && reply.result.Ok.type === 'actions');
  const [action] = reply.result.Ok.actions;
  assert(action);
  assertEquals(action.aliases, ['pdf reader', 'open document', 'pdf open', 'read pdf']);
  await plugin.palette({type: 'execute', scope: {...scope, revision: 2}, context, handle: action.handle, values: null}, 1);
  const launches = () => plugin.commands.filter((c): c is {RunAction: [{LaunchOrFocusPlugin: {plugin: {Alias: {name: string; configuration: Record<string, string>}}}}, unknown]} => typeof c === 'object' && c !== null && 'RunAction' in c);
  const launch = launches()[0];
  assert(launch);
  const alias = launch.RunAction[0].LaunchOrFocusPlugin.plugin.Alias;
  assertEquals(alias.name, 'file-finder');
  assertEquals(alias.configuration['overlay'], 'true');
  assertEquals(alias.configuration['fzf_args'], undefined);
  assertEquals(JSON.parse(alias.configuration['openers_json']!), {pdf: {plugin: import.meta.resolve('./main.ts'), message: 'open'}});
  await plugin.palette({type: 'release', handles: [action.handle]}, 1);
  await plugin.palette({type: 'dismiss', opening: 1}, 1);
  await plugin.palette({type: 'execute', scope: {...scope, revision: 3}, context, handle: action.handle, values: null}, 1);
  assertEquals(launches().length, 1);
  const reopened = {...scope, opening: 2};
  await plugin.palette({type: 'discover', scope: reopened, context, query: '', source: null}, 1);
  const again = plugin.paletteCommands.at(-1);
  assert(again?.type === 'reply' && 'Ok' in again.result && again.result.Ok.type === 'actions');
  const fresh = again.result.Ok.actions[0];
  assert(fresh);
  await plugin.palette({type: 'dismiss', opening: 2}, 1);
  await plugin.palette({type: 'execute', scope: {...reopened, revision: 2}, context, handle: fresh.handle, values: null}, 1);
  assertEquals(launches().length, 1);
});

